-- STEP 9: 리드타임 정책화와 예측 기반 재고 Projection
-- 원천(raw) 데이터는 수정하지 않고 core/analytics 조회 계층만 확장합니다.
-- 확정수주 정책: Forecast는 기본 수요, 확정수주는 별도 확정수요 overlay로 취급합니다.
-- Forecast 결과에 확정수주를 다시 합산하지 않는 운영 계약을 전제로 하며,
-- Projection에서는 두 값을 별도 컬럼으로 유지해 한 소스가 다른 소스에 합쳐지지 않게 합니다.

create table if not exists core.leadtime_plan_history (
  history_id bigint generated by default as identity primary key,
  supplier_id text not null,
  before_planned_lead_time integer,
  after_planned_lead_time integer,
  before_basis text,
  after_basis text,
  before_service_level numeric,
  after_service_level numeric,
  before_confirmed_reason text,
  after_confirmed_reason text,
  changed_by uuid,
  changed_at timestamptz not null default now(),
  before_state jsonb,
  after_state jsonb
);

create index if not exists leadtime_plan_history_supplier_idx
  on core.leadtime_plan_history(supplier_id, changed_at desc);

alter table core.leadtime_plan_history enable row level security;
drop policy if exists leadtime_plan_history_select_admin on core.leadtime_plan_history;
create policy leadtime_plan_history_select_admin
  on core.leadtime_plan_history for select to authenticated
  using (core.is_admin());
revoke all on core.leadtime_plan_history from anon;
grant select on core.leadtime_plan_history to authenticated;

create or replace function core.audit_leadtime_plan_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_before jsonb;
  v_after jsonb;
  v_supplier_id text;
  v_actor uuid;
begin
  v_before := case when tg_op = 'INSERT' then null else jsonb_build_object(
    'supplier_id', old.supplier_id,
    'planned_lead_time', old.planned_lead_time,
    'basis', old.basis,
    'service_level', old.service_level,
    'confirmed_reason', old.confirmed_reason,
    'confirmed_at', old.confirmed_at
  ) end;
  v_after := case when tg_op = 'DELETE' then null else jsonb_build_object(
    'supplier_id', new.supplier_id,
    'planned_lead_time', new.planned_lead_time,
    'basis', new.basis,
    'service_level', new.service_level,
    'confirmed_reason', new.confirmed_reason,
    'confirmed_at', new.confirmed_at
  ) end;
  v_supplier_id := coalesce(new.supplier_id, old.supplier_id);
  v_actor := auth.uid();

  insert into core.leadtime_plan_history (
    supplier_id,
    before_planned_lead_time,
    after_planned_lead_time,
    before_basis,
    after_basis,
    before_service_level,
    after_service_level,
    before_confirmed_reason,
    after_confirmed_reason,
    changed_by,
    before_state,
    after_state
  )
  values (
    v_supplier_id,
    case when tg_op = 'INSERT' then null else old.planned_lead_time end,
    case when tg_op = 'DELETE' then null else new.planned_lead_time end,
    case when tg_op = 'INSERT' then null else old.basis end,
    case when tg_op = 'DELETE' then null else new.basis end,
    case when tg_op = 'INSERT' then null else old.service_level end,
    case when tg_op = 'DELETE' then null else new.service_level end,
    case when tg_op = 'INSERT' then null else old.confirmed_reason end,
    case when tg_op = 'DELETE' then null else new.confirmed_reason end,
    v_actor,
    v_before,
    v_after
  );

  insert into core.audit_log (actor, action, target_type, target_id, before, after)
  values (v_actor, 'LEADTIME_POLICY_CHANGED', 'leadtime_plan', v_supplier_id, v_before, v_after);

  return coalesce(new, old);
end;
$$;

revoke all on function core.audit_leadtime_plan_change() from public;

drop trigger if exists leadtime_plan_audit on core.leadtime_plan;
create trigger leadtime_plan_audit
  after insert or update or delete on core.leadtime_plan
  for each row execute function core.audit_leadtime_plan_change();

