create view core.v_leadtime_effective as
with supplier_master as (
  select upper(trim("공급업체코드")) as supplier_id,
         max(nullif(trim("공급업체명"), '')) as supplier_name,
         max(nullif(trim("국가"), '')) as country
    from raw.supplier_master
   group by upper(trim("공급업체코드"))
), supplier_ids as (
  select supplier_id from core.v_leadtime_stat
  union
  select upper(trim(supplier_id)) from core.leadtime_plan
)
select ids.supplier_id,
       coalesce(st.supplier_name, sm.supplier_name, ids.supplier_id) as supplier_name,
       coalesce(st.country, sm.country) as country,
       st.n_samples,
       st.mean_days,
       st.p50_days,
       st.p80_days,
       st.p90_days,
       p.planned_lead_time,
       coalesce(p.planned_lead_time, st.p80_days) as effective_lead_time,
       case
         when p.planned_lead_time is not null then 'ADMIN_CONFIRMED'
         when st.p80_days is not null then 'ACTUAL_P80'
         else null
       end as source,
       p.basis,
       p.service_level,
       p.confirmed_reason,
       p.confirmed_at
  from supplier_ids ids
  left join core.v_leadtime_stat st on st.supplier_id = ids.supplier_id
  left join supplier_master sm on sm.supplier_id = ids.supplier_id
  left join core.leadtime_plan p on upper(trim(p.supplier_id)) = ids.supplier_id;

create view core.v_inventory_snapshot as
with parsed as (
  select upper(regexp_replace(trim("품목코드"), '[\\s\\-_]', '', 'g')) as item_id,
         nullif(regexp_replace(trim("현재고"), '[^0-9.\\-]', '', 'g'), '')::numeric as current_stock,
         nullif(trim("기준일자"), '')::date as inventory_as_of
    from raw.inventory
), latest as (
  select max(inventory_as_of) as inventory_as_of from parsed
)
select p.item_id,
       sum(p.current_stock) as current_stock,
       l.inventory_as_of
  from parsed p
  cross join latest l
 where p.inventory_as_of = l.inventory_as_of
 group by p.item_id, l.inventory_as_of;

create view core.v_inbound_schedule as
with inventory_asof as (
  select max(nullif(trim("기준일자"), '')::date) as inventory_as_of
    from raw.inventory
), scheduled as (
  select f.item_id,
         f.supplier_id,
         f.qty as scheduled_qty,
         f.order_date,
         f.due_date,
         l.effective_lead_time,
         a.inventory_as_of,
         coalesce(f.due_date, f.order_date + l.effective_lead_time) as planned_receipt_date
    from core.v_fact_shipment f
    cross join inventory_asof a
    left join core.v_leadtime_effective l on l.supplier_id = f.supplier_id
   where f.status = 'IN_TRANSIT'
     and f.qty is not null
     and f.qty > 0
)
select item_id,
       supplier_id,
       scheduled_qty,
       case
         when planned_receipt_date is null then null
         when inventory_as_of is not null and planned_receipt_date <= inventory_as_of then inventory_as_of
         else planned_receipt_date
       end as scheduled_receipt_date,
       case when planned_receipt_date is null then 'NO_LEADTIME' else 'SCHEDULED' end as reason_code,
       order_date,
       due_date,
       effective_lead_time
  from scheduled;

create view core.v_inbound_qty as
select item_id,
       sum(scheduled_qty) as inbound_qty,
       count(*) as inbound_shipments,
       min(scheduled_receipt_date) as earliest_eta
  from core.v_inbound_schedule
 where scheduled_receipt_date is not null
 group by item_id;

create view core.v_confirmed_sales_order as
select upper(regexp_replace(trim(item_id), '[\\s\\-_]', '', 'g')) as item_id,
       coalesce(requested_delivery_date, order_date) as demand_date,
       ordered_qty as confirmed_qty,
       sales_order_no,
       line_no,
       status
  from raw.sales_order
 where ordered_qty is not null
   and ordered_qty > 0
   and coalesce(requested_delivery_date, order_date) is not null
   and upper(trim(coalesce(status, ''))) in ('CONFIRMED', 'CONFIRMED_ORDER', '확정', '확정수주');

create view core.v_soft_allocation as
select upper(regexp_replace(trim(item_id), '[\\s\\-_]', '', 'g')) as item_id,
       event_date as allocation_date,
       quantity as allocated_qty,
       event_id,
       event_type,
       status
  from raw.business_event
 where quantity is not null
   and quantity > 0
   and event_date is not null
   and upper(replace(trim(coalesce(event_type, '')), ' ', '_')) in (
     'SOFT_ALLOCATION', 'SOFT_ALLOCATED', 'RESERVATION', '가예약'
   )
   and upper(trim(coalesce(status, ''))) not in ('CANCELLED', 'CANCELED', 'CLOSED', 'EXCLUDED', '취소', '종료');

grant select on core.v_leadtime_effective, core.v_inventory_snapshot,
