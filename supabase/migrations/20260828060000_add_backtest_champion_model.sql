-- STEP 7: 저장된 Forecast Result와 분리된 검증 Actual을 이용한
-- 백테스트, 모델 성능, Champion 이력 구조입니다.
--
-- 원칙
-- 1. Forecast를 다시 계산하지 않습니다. core.forecast_result만 읽습니다.
-- 2. 검증 Actual은 core.v_test_actual만 사용합니다.
-- 3. 채점은 이 SQL 함수에서 수행하며 화면 컴포넌트에는 계산식을 두지 않습니다.
-- 4. Champion은 삭제/갱신하지 않고 선택 이력을 누적합니다.

create table if not exists core.model_config (
  model_id text not null,
  model_version text not null,
  model_name text not null,
  description text,
  enabled boolean not null default true,
  is_baseline boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (model_id, model_version)
);

create table if not exists core.forecast_result (
  forecast_result_id bigint generated by default as identity primary key,
  forecast_run_id uuid not null references core.forecast_run(forecast_run_id) on delete cascade,
  model_id text not null,
  model_version text not null,
  item_id text not null,
  forecast_date date not null,
  forecast_value numeric,
  p50 numeric,
  p80 numeric,
  p90 numeric,
  prediction_lower numeric,
  prediction_upper numeric,
  result_reason_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (forecast_run_id, model_id, model_version, item_id, forecast_date),
  constraint forecast_result_model_fk foreign key (model_id, model_version)
    references core.model_config(model_id, model_version)
);

create table if not exists core.backtest_run (
  backtest_run_id uuid primary key default gen_random_uuid(),
  forecast_run_id uuid not null references core.forecast_run(forecast_run_id),
  test_start date not null,
  test_end date not null,
  metric text not null,
  status text not null default 'RUNNING',
  triggered_by uuid references auth.users(id) on delete set null,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  error_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint backtest_run_metric_ck check (metric in ('WAPE', 'MAPE', 'RMSE', 'MAE')),
  constraint backtest_run_status_ck check (status in ('RUNNING', 'COMPLETED', 'FAILED')),
  constraint backtest_run_range_ck check (test_start <= test_end)
);

create table if not exists core.model_performance (
  performance_id bigint generated by default as identity primary key,
  backtest_run_id uuid not null references core.backtest_run(backtest_run_id) on delete cascade,
  forecast_run_id uuid not null references core.forecast_run(forecast_run_id),
  model_id text not null,
  model_version text not null,
  item_id text not null,
  test_start date not null,
  test_end date not null,
  metric text not null,
  periods_total integer not null default 0,
  actual_periods integer not null default 0,
  forecast_periods integer not null default 0,
  comparable_periods integer not null default 0,
  actual_abs_sum numeric,
  wape numeric,
  mape numeric,
  bias numeric,
  rmse numeric,
  mae numeric,
  metric_value numeric,
  baseline_improvement numeric,
  rank integer,
  status text not null,
  reason_code text,
  calculated_at timestamptz not null default now(),
  constraint model_performance_metric_ck check (metric in ('WAPE', 'MAPE', 'RMSE', 'MAE')),
  constraint model_performance_status_ck check (status in ('VALID', 'CALCULATION_UNAVAILABLE')),
  constraint model_performance_model_fk foreign key (model_id, model_version)
    references core.model_config(model_id, model_version),
  unique (backtest_run_id, model_id, model_version, item_id)
);

create table if not exists core.champion_model (
