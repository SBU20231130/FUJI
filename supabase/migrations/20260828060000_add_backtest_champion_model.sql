  select count(*) filter (where enabled = true) as enabled_outlier_rule_count,
         count(*) filter (where enabled = true and learning_excluded = true) as learning_excluded_rule_count
    from core.outlier_rule
)
select c.*, p.policy_key as default_policy_key, p.service_level as default_service_level,
       p.review_period_days as default_review_period_days, p.safety_buffer_days as default_safety_buffer_days,
       p.config_value as default_policy_value, ic.active_item_policy_count,
       rc.enabled_outlier_rule_count, rc.learning_excluded_rule_count,
       s.champion_metric, s.baseline_model_id, s.baseline_model_version
  from analytics.v_data_coverage as c
  left join core.policy_config as p on p.policy_key = 'DEFAULT' and p.active = true
  join core.forecast_setting as s on s.setting_key = c.setting_key
  cross join item_counts as ic
  cross join rule_counts as rc;

