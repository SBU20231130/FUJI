-- 검증 단계에서 supplier master 존재 여부를 확인할 수 있는 정제 view입니다.
create or replace view core.v_supplier_master as
select
  nullif(trim("공급업체코드"), '') as supplier_id,
  nullif(trim("공급업체명"), '') as supplier_name,
  nullif(trim("국가"), '') as country,
  nullif(trim("표준리드타임(일)"), '') as standard_lead_time,
  nullif(trim("사용여부"), '') as is_active
from raw.supplier_master
where nullif(trim("공급업체코드"), '') is not null;

-- import type별 실제 raw 대상 컬럼. identity PK는 insert 시 제외하거나 rollback 복구 시 포함합니다.
create or replace function core.import_target_columns(p_import_type text, p_include_identity boolean default false)
returns text[]
language sql
immutable
set search_path = ''
as $$
  select case
    when p_import_type = 'usage_history' then array['usage_id','item_id','use_date','qty','warehouse','note','batch_id','source_type','loaded_at','source_record_id']::text[]
    when p_import_type = 'inventory' then array['품목코드','창고','현재고','기준일자','안전재고','batch_id','source_type','loaded_at','source_record_id']::text[]
    when p_import_type = 'item_master' then array['품목코드','품목명','품목구분','단위','표준단가','사용여부','supplier_id','batch_id','source_type','loaded_at','source_record_id']::text[]
    when p_import_type = 'supplier_master' then array['공급업체코드','공급업체명','국가','표준리드타임(일)','담당자','사용여부','batch_id','source_type','loaded_at','source_record_id']::text[]
    when p_import_type = 'purchase_order' then array['발주번호','발주일','공급업체','품목코드','발주수량','단가','납기예정일','발주담당','batch_id','source_type','loaded_at','source_record_id']::text[]
    when p_import_type = 'goods_receipt' then array['입고번호','발주번호','품목코드','입고수량','입고일','입고창고','batch_id','source_type','loaded_at','source_record_id']::text[]
    when p_import_type = 'sales_order' then case when p_include_identity then array['id','sales_order_no','line_no','order_date','item_id','supplier_id','customer_id','ordered_qty','requested_delivery_date','status','batch_id','source_type','loaded_at','source_record_id']::text[] else array['sales_order_no','line_no','order_date','item_id','supplier_id','customer_id','ordered_qty','requested_delivery_date','status','batch_id','source_type','loaded_at','source_record_id']::text[] end
    when p_import_type = 'business_event' then case when p_include_identity then array['id','event_id','event_type','event_date','item_id','quantity','description','status','batch_id','source_type','loaded_at','source_record_id']::text[] else array['event_id','event_type','event_date','item_id','quantity','description','status','batch_id','source_type','loaded_at','source_record_id']::text[] end
    when p_import_type = 'item_substitute' then case when p_include_identity then array['id','item_id','substitute_item_id','priority','valid_from','valid_to','reason','active','batch_id','source_type','loaded_at','source_record_id']::text[] else array['item_id','substitute_item_id','priority','valid_from','valid_to','reason','active','batch_id','source_type','loaded_at','source_record_id']::text[] end
    else null
  end;
$$;

-- 검증 완료된 JSON 행을 whitelist된 raw 테이블에만 저장합니다.
-- 이 함수는 admin 확인을 다시 하고, replace/upsert의 이전 데이터도 backup합니다.
create or replace function core.import_batch_rows(p_batch_id uuid, p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_batch core.upload_batch%rowtype;
  v_target text;
  v_columns text[];
  v_columns_sql text;
  v_select_sql text;
  v_row jsonb;
  v_previous jsonb;
  v_source_record_id text;
  v_imported integer := 0;
begin
  if not (select core.is_admin()) then
    raise exception 'ADMIN_REQUIRED' using errcode = '42501';
  end if;

  select * into v_batch
    from core.upload_batch
   where batch_id = p_batch_id
   for update;
  if not found then raise exception 'BATCH_NOT_FOUND'; end if;
  if v_batch.status not in ('VALIDATED', 'VALIDATED_WITH_ERRORS', 'IMPORTING') then
    raise exception 'BATCH_NOT_READY';
  end if;
  if jsonb_typeof(p_rows) <> 'array' then raise exception 'ROWS_MUST_BE_ARRAY'; end if;

  v_target := case v_batch.import_type
    when 'usage_history' then 'usage_history'
    when 'inventory' then 'inventory'
    when 'item_master' then 'item_master'
    when 'supplier_master' then 'supplier_master'
    when 'purchase_order' then 'purchase_order'
    when 'goods_receipt' then 'goods_receipt'
    when 'sales_order' then 'sales_order'
    when 'business_event' then 'business_event'
    when 'item_substitute' then 'item_substitute'
    else null
  end;
  if v_target is null then raise exception 'IMPORT_TYPE_NOT_ALLOWED'; end if;

  if v_batch.import_mode = 'replace' and v_batch.replace_snapshot_at is null then
    execute format(
      'insert into core.import_backup(batch_id,target_table,source_record_id,previous_data)
       select $1,$2,source_record_id,to_jsonb(t) from raw.%I t', v_target
    ) using p_batch_id, v_target;
    execute format('delete from raw.%I', v_target);
    update core.upload_batch set replace_snapshot_at = now(), status = 'IMPORTING', updated_at = now() where batch_id = p_batch_id;
  end if;

  v_columns := core.import_target_columns(v_batch.import_type, false);
  v_columns_sql := array_to_string(array(select quote_ident(c) from unnest(v_columns) as c), ',');
  v_select_sql := array_to_string(array(select format('(r).%I', c) from unnest(v_columns) as c), ',');

  for v_row in select value from jsonb_array_elements(p_rows) loop
    v_source_record_id := nullif(v_row ->> 'source_record_id', '');
    if v_source_record_id is null then raise exception 'SOURCE_RECORD_ID_REQUIRED'; end if;
    if not exists (
      select 1
        from core.import_staging as s
       where s.batch_id = p_batch_id
         and s.validation_status in ('SUCCESS', 'WARNING')
         and s.mapped_data = v_row
    ) then
      raise exception 'ROW_NOT_VALIDATED' using errcode = '22023';
    end if;

    if v_batch.import_mode = 'upsert' then
      execute format(
        'select coalesce(jsonb_agg(to_jsonb(t)), ''[]''::jsonb) from raw.%I t where source_record_id = $1', v_target
      ) into v_previous using v_source_record_id;
      if jsonb_array_length(v_previous) > 0 then
        insert into core.import_backup(batch_id,target_table,source_record_id,previous_data)
        select p_batch_id, v_target, v_source_record_id, jsonb_array_elements(v_previous);
      end if;
      execute format('delete from raw.%I where source_record_id = $1', v_target) using v_source_record_id;
    end if;

    execute format(
      'insert into raw.%I (%s)
       select %s from jsonb_populate_record(null::raw.%I, $1) as r',
      v_target, v_columns_sql, v_select_sql, v_target
    ) using v_row;
    v_imported := v_imported + 1;
  end loop;

  if v_batch.import_type in ('usage_history','sales_order','business_event','item_substitute') then
    update core.forecast_run
       set stale = true,
           status = 'STALE',
           stale_reason = coalesce(stale_reason, 'NEW_FILE_UPLOAD:' || p_batch_id::text),
           stale_at = coalesce(stale_at, now()),
           updated_at = now()
     where stale = false;
  end if;
  return v_imported;
end;
$$;

-- batch_id 범위만 제거하고, upsert/replace의 이전 snapshot은 복구합니다.
create or replace function core.rollback_batch(p_batch_id uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_batch core.upload_batch%rowtype;
  v_target text;
  v_columns text[];
  v_columns_sql text;
  v_select_sql text;
  v_backup record;
  v_deleted integer := 0;
begin
  if not (select core.is_admin()) then
    raise exception 'ADMIN_REQUIRED' using errcode = '42501';
  end if;
  select * into v_batch from core.upload_batch where batch_id = p_batch_id for update;
  if not found then raise exception 'BATCH_NOT_FOUND'; end if;
  if v_batch.status = 'ROLLED_BACK' then return 0; end if;
  if v_batch.status not in ('IMPORTED','FAILED','IMPORTING') then raise exception 'BATCH_NOT_IMPORTED'; end if;

  v_target := case v_batch.import_type
    when 'usage_history' then 'usage_history'
    when 'inventory' then 'inventory'
    when 'item_master' then 'item_master'
    when 'supplier_master' then 'supplier_master'
    when 'purchase_order' then 'purchase_order'
    when 'goods_receipt' then 'goods_receipt'
    when 'sales_order' then 'sales_order'
    when 'business_event' then 'business_event'
    when 'item_substitute' then 'item_substitute'
    else null
  end;
  if v_target is null then raise exception 'IMPORT_TYPE_NOT_ALLOWED'; end if;

  execute format('delete from raw.%I where batch_id = $1', v_target) using p_batch_id;
  get diagnostics v_deleted = row_count;

  if v_batch.import_mode in ('upsert','replace') then
    v_columns := core.import_target_columns(v_batch.import_type, true);
    v_columns_sql := array_to_string(array(select quote_ident(c) from unnest(v_columns) as c), ',');
    v_select_sql := array_to_string(array(select format('(r).%I', c) from unnest(v_columns) as c), ',');
    for v_backup in select previous_data from core.import_backup where batch_id = p_batch_id order by backup_id loop
      execute format(
        'insert into raw.%I (%s)
         select %s from jsonb_populate_record(null::raw.%I, $1) as r',
        v_target, v_columns_sql, v_select_sql, v_target
      ) using v_backup.previous_data;
    end loop;
  end if;

  update core.upload_batch
     set status = 'ROLLED_BACK', rolled_back_at = now(), updated_at = now()
   where batch_id = p_batch_id;
  return v_deleted;
end;
$$;

