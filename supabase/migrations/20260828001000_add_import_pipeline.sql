-- STEP 4: CSV/Excel 적재 staging, 검증 오류, 이력, rollback 구조

create schema if not exists core;

create table if not exists core.upload_batch (
  batch_id uuid primary key default gen_random_uuid(),
  file_name text not null,
  import_type text not null,
  import_mode text not null,
  total_rows integer not null default 0,
  success_rows integer not null default 0,
  warning_rows integer not null default 0,
  error_rows integer not null default 0,
  status text not null default 'STAGED',
  uploaded_by uuid not null references auth.users(id),
  uploaded_at timestamptz not null default now(),
  imported_at timestamptz,
  rolled_back_at timestamptz,
  replace_snapshot_at timestamptz,
  error_message text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint upload_batch_import_type_ck check (import_type in (
    'usage_history', 'inventory', 'item_master', 'supplier_master',
    'purchase_order', 'goods_receipt', 'sales_order',
    'business_event', 'item_substitute'
  )),
  constraint upload_batch_import_mode_ck check (import_mode in ('append', 'upsert', 'replace')),
  constraint upload_batch_status_ck check (status in (
    'STAGED', 'VALIDATING', 'VALIDATED', 'VALIDATED_WITH_ERRORS',
    'IMPORTING', 'IMPORTED', 'ROLLED_BACK', 'FAILED'
  )),
  constraint upload_batch_counts_ck check (
    total_rows >= 0 and success_rows >= 0 and warning_rows >= 0 and error_rows >= 0
  )
);

create table if not exists core.import_staging (
  staging_id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade,
  row_number integer not null,
  original_data jsonb not null,
  mapped_data jsonb,
  validation_status text not null default 'PENDING',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (batch_id, row_number),
  constraint import_staging_row_number_ck check (row_number > 1),
  constraint import_staging_status_ck check (validation_status in ('PENDING', 'SUCCESS', 'WARNING', 'ERROR'))
);

create table if not exists core.column_mapping (
  mapping_id bigint generated by default as identity primary key,
  import_type text not null,
  source_column text not null,
  target_field text not null,
  created_by uuid references auth.users(id) on delete set null,
  usage_count integer not null default 1,
  last_used_at timestamptz not null default now(),
  unique (import_type, source_column, target_field)
);

create table if not exists core.validation_error (
  error_id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade,
  staging_id bigint references core.import_staging(staging_id) on delete cascade,
  row_number integer not null,
  field_name text,
  error_code text not null,
  error_message text not null,
  severity text not null,
  original_value text,
  created_at timestamptz not null default now(),
  constraint validation_error_severity_ck check (severity in ('WARNING', 'ERROR'))
);

create table if not exists core.import_backup (
  backup_id bigint generated by default as identity primary key,
  batch_id uuid not null references core.upload_batch(batch_id) on delete cascade,
  target_table text not null,
  source_record_id text,
  previous_data jsonb not null,
  created_at timestamptz not null default now()
);

-- 현재 프로젝트에는 Forecast Run 테이블이 없어 STEP 6에서 사용할 최소 계약을 준비합니다.
-- 결과 자체는 삭제하지 않고 새 수요 적재 시 stale만 표시합니다.
create table if not exists core.forecast_run (
  forecast_run_id uuid primary key default gen_random_uuid(),
  data_snapshot_at timestamptz not null,
  status text not null default 'READY',
  stale boolean not null default false,
  stale_reason text,
  stale_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint forecast_run_status_ck check (status in ('READY', 'STALE', 'FAILED'))
);

create index if not exists upload_batch_uploaded_at_idx on core.upload_batch(uploaded_at desc);
create index if not exists upload_batch_status_idx on core.upload_batch(status);
create index if not exists import_staging_batch_idx on core.import_staging(batch_id, row_number);
create index if not exists validation_error_batch_idx on core.validation_error(batch_id, severity, row_number);
create index if not exists validation_error_staging_idx on core.validation_error(staging_id);
create index if not exists import_backup_batch_idx on core.import_backup(batch_id, target_table);
create index if not exists forecast_run_snapshot_idx on core.forecast_run(data_snapshot_at desc);
create index if not exists upload_batch_uploaded_by_idx on core.upload_batch(uploaded_by);
create index if not exists column_mapping_created_by_idx on core.column_mapping(created_by);

drop trigger if exists upload_batch_set_updated_at on core.upload_batch;
