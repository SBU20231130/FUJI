-- 실제 데이터 범위와 설정 범위를 한 줄에서 점검합니다.
create or replace view analytics.v_data_coverage as
with bounds as (
  select min(use_date) as data_start, max(use_date) as data_end
  from raw.usage_history
), settings as (
  select * from core.forecast_setting where setting_key = 'DEFAULT' limit 1
), counts as (
  select
    count(*) filter (where f.train_start is not null and f.train_end is not null and u.use_date between f.train_start and f.train_end) as train_row_count,
    count(*) filter (where f.test_start is not null and f.test_end is not null and u.use_date between f.test_start and f.test_end) as test_row_count,
    count(*) filter (where f.train_start is not null and f.train_end is not null and f.test_start is not null and f.test_end is not null and u.use_date between f.train_start and f.train_end and u.use_date between f.test_start and f.test_end) as overlap_row_count
  from raw.usage_history as u
  left join settings as f on true
)
select
  s.setting_key,
  b.data_start,
  b.data_end,
  s.train_start,
  s.train_end,
  s.test_start,
  s.test_end,
  s.granularity,
  c.train_row_count,
  c.test_row_count,
  c.overlap_row_count,
  (
    b.data_start is not null
    and b.data_end is not null
    and s.train_start is not null
    and s.train_end is not null
    and s.train_start >= b.data_start
    and s.train_end <= b.data_end
    and s.train_start <= s.train_end
    and c.train_row_count > 0
  ) as train_window_ok,
  (
    b.data_start is not null
    and b.data_end is not null
    and s.test_start is not null
    and s.test_end is not null
    and s.test_start >= b.data_start
    and s.test_end <= b.data_end
    and s.test_start <= s.test_end
    and c.test_row_count > 0
  ) as test_window_ok,
  (c.overlap_row_count = 0) as isolation_ok
from bounds as b
left join settings as s on true
cross join counts as c;

-- 관리자 화면이 한 번의 조회로 기간·격리·정책 상태를 확인하도록 하는 조회용 view입니다.
create or replace view analytics.v_forecast_settings as
with item_counts as (
  select count(*) filter (where active = true) as active_item_policy_count
  from core.item_policy
), rule_counts as (
  select
    count(*) filter (where enabled = true) as enabled_outlier_rule_count,
    count(*) filter (where enabled = true and learning_excluded = true) as learning_excluded_rule_count
  from core.outlier_rule
)
select
  c.*,
  p.policy_key as default_policy_key,
  p.service_level as default_service_level,
  p.review_period_days as default_review_period_days,
  p.safety_buffer_days as default_safety_buffer_days,
  p.config_value as default_policy_value,
  ic.active_item_policy_count,
  rc.enabled_outlier_rule_count,
  rc.learning_excluded_rule_count
from analytics.v_data_coverage as c
left join core.policy_config as p
  on p.policy_key = 'DEFAULT'
 and p.active = true
cross join item_counts as ic
cross join rule_counts as rc;

-- Demand Profile은 raw.usage_history를 직접 보지 않고 학습 view만 사용합니다.
-- 기존 평균/표준편차 계산식은 유지하고, DB outlier_rule로 제외 범위를 관리합니다.
create or replace view core.v_usage_effective as
with deduped as (
  select
    d.*,
    row_number() over (
      partition by upper(regexp_replace(coalesce(d.item_id, ''), '[\\s\\-_]', '', 'g')), d.use_date, d.qty, d.warehouse, d.note
      order by d.usage_id
    ) as duplicate_rank
  from core.v_train_demand as d
), filtered as (
  select d.*
  from deduped as d
  where not exists (
    select 1 from core.outlier_rule as r
    where r.enabled = true
      and r.learning_excluded = true
      and r.rule_type = 'DUPLICATE'
      and d.duplicate_rank > 1
  )
  and not exists (
    select 1 from core.outlier_rule as r
    where r.enabled = true
      and r.learning_excluded = true
      and r.rule_type = 'RETURN'
      and d.qty < 0
  )
  and not exists (
    select 1 from core.outlier_rule as r
    where r.enabled = true
      and r.learning_excluded = true
      and r.rule_type = 'PROJECT'
      and coalesce(r.condition ->> 'note_contains', '') <> ''
      and coalesce(d.note, '') ilike '%' || (r.condition ->> 'note_contains') || '%'
  )
), calc as (
  select
    upper(regexp_replace(f.item_id, '[\\s\\-_]', '', 'g')) as item_id,
    count(*) as valid_days,
    round(avg(f.qty), 2) as daily_usage_avg,
    round(stddev_samp(f.qty), 2) as daily_usage_sd
  from filtered as f
  where f.item_id is not null
    and f.qty is not null
  group by upper(regexp_replace(f.item_id, '[\\s\\-_]', '', 'g'))
)
select
  c.item_id,
  coalesce(p.valid_days::bigint, c.valid_days) as valid_days,
  coalesce(p.daily_usage_avg, c.daily_usage_avg) as daily_usage_avg,
  coalesce(p.daily_usage_sd, c.daily_usage_sd) as daily_usage_sd,
  round(coalesce(p.daily_usage_avg, c.daily_usage_avg), 2) as usage_used,
  round(coalesce(p.daily_usage_sd, c.daily_usage_sd) / nullif(coalesce(p.daily_usage_avg, c.daily_usage_avg), 0::numeric), 2) as cv,
  case when p.item_id is not null then '확정값' else '정제 기준' end as source
from calc as c
left join core.usage_profile as p on p.item_id = c.item_id;

