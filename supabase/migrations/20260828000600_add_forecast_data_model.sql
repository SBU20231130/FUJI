-- 날짜를 애플리케이션 코드에 고정하지 않고 현재 적재 데이터의 경계로 초기값을 만듭니다.
with bounds as (
  select
    min(use_date) as data_start,
    max(use_date) as data_end,
    min(use_date) + greatest(1, floor((max(use_date) - min(use_date)) * 0.8)::integer) as split_date
  from raw.usage_history
  where use_date is not null
)
update core.forecast_setting as f
   set train_start = b.data_start,
       train_end = b.split_date - 1,
       test_start = b.split_date,
       test_end = b.data_end,
       updated_at = now()
  from bounds as b
 where f.setting_key = 'DEFAULT'
   and f.train_start is null
   and b.data_start is not null
   and b.data_end > b.data_start;

-- Forecast와 Demand Profile의 입력 경계를 DB 설정값으로 고정합니다.
create or replace view core.v_train_demand as
select
  f.setting_key,
  u.usage_id,
  u.item_id,
  u.use_date,
  u.qty,
  u.warehouse,
  u.note,
  u.batch_id,
  u.source_type,
  u.loaded_at,
  u.source_record_id
from raw.usage_history as u
join core.forecast_setting as f
  on f.setting_key = 'DEFAULT'
 and f.active = true
where f.train_start is not null
  and f.train_end is not null
  and u.use_date between f.train_start and f.train_end;

