-- STEP 2: Auth 사용자 프로필, RBAC, 감사 로그
--
-- 원칙
-- 1. auth.users는 Supabase Auth가 관리하고, 업무용 사용자 정보는 core.app_user에 둡니다.
-- 2. 권한은 클라이언트가 아닌 core.is_admin()과 RLS가 판정합니다.
-- 3. 기존 raw/analytics 계산 SQL은 변경하지 않습니다.

create schema if not exists core;

create table if not exists core.app_user (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text not null default '',
  department text,
  role text not null default 'USER' check (role in ('ADMIN', 'USER')),
  active boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists app_user_email_uidx on core.app_user(lower(email));

create table if not exists core.audit_log (
  id bigint generated by default as identity primary key,
  actor uuid references auth.users(id) on delete set null,
  action text not null,
  target_type text not null,
  target_id text not null,
  before jsonb,
  after jsonb,
  "at" timestamptz not null default now()
);

create index if not exists audit_log_target_idx on core.audit_log(target_type, target_id);
create index if not exists audit_log_at_idx on core.audit_log("at" desc);

create or replace function core.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists app_user_set_updated_at on core.app_user;
create trigger app_user_set_updated_at
before update on core.app_user
for each row execute function core.set_updated_at();

-- RLS와 trigger에서 함께 사용하는 DB 권한 판정 함수입니다.
create or replace function core.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from core.app_user as u
    where u.user_id = (select auth.uid())
      and u.role = 'ADMIN'
      and u.active = true
  );
$$;

-- 로그인 직후 last_login_at만 갱신합니다. 직접 UPDATE 권한은 주지 않습니다.
create or replace function core.touch_last_login()
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  update core.app_user
     set last_login_at = now(), updated_at = now()
   where user_id = (select auth.uid())
     and active = true;
$$;

-- Auth 사용자 생성 시 업무용 프로필을 자동으로 만듭니다.
create or replace function core.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  display_name text;
begin
  display_name := coalesce(
    new.raw_user_meta_data ->> 'name',
    new.raw_user_meta_data ->> 'full_name',
    split_part(coalesce(new.email, ''), '@', 1),
    ''
  );

  insert into core.app_user (user_id, email, name)
  values (new.id, coalesce(new.email, ''), display_name)
  on conflict (user_id) do update
    set email = excluded.email,
        updated_at = now();

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_app_user on auth.users;
create trigger on_auth_user_created_app_user
after insert on auth.users
for each row execute function core.handle_new_user();

-- migration 적용 시점에 이미 존재하는 Auth 사용자도 보정합니다.
insert into core.app_user (user_id, email, name)
select
  u.id,
  coalesce(u.email, ''),
  coalesce(
    u.raw_user_meta_data ->> 'name',
    u.raw_user_meta_data ->> 'full_name',
    split_part(coalesce(u.email, ''), '@', 1),
    ''
  )
from auth.users as u
on conflict (user_id) do update
  set email = excluded.email,
      updated_at = now();

-- role/active 변경은 DB에서 자기 자신을 잠그지 못하도록 막습니다.
create or replace function core.prevent_self_lockout()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is not null
     and old.user_id = (select auth.uid())
     and (new.role is distinct from old.role or new.active is distinct from old.active) then
    raise exception 'SELF_LOCKOUT_FORBIDDEN'
      using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists app_user_prevent_self_lockout on core.app_user;
create trigger app_user_prevent_self_lockout
before update on core.app_user
for each row execute function core.prevent_self_lockout();

-- 관리자 변경은 서버 코드가 우회하지 못하도록 DB trigger에서 반드시 기록합니다.
create or replace function core.audit_app_user_changes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  change_action text;
begin
  if new.role is not distinct from old.role
     and new.active is not distinct from old.active then
    return new;
  end if;

  change_action := case
    when new.role is distinct from old.role and new.active is distinct from old.active
      then 'APP_USER_ROLE_AND_STATUS_CHANGED'
    when new.role is distinct from old.role
      then 'APP_USER_ROLE_CHANGED'
    else 'APP_USER_STATUS_CHANGED'
  end;

  insert into core.audit_log (actor, action, target_type, target_id, before, after)
  values (
    (select auth.uid()),
    change_action,
    'app_user',
    new.user_id::text,
    jsonb_build_object('role', old.role, 'active', old.active),
    jsonb_build_object('role', new.role, 'active', new.active)
  );

  return new;
end;
$$;

drop trigger if exists app_user_audit_changes on core.app_user;
create trigger app_user_audit_changes
after update on core.app_user
for each row execute function core.audit_app_user_changes();

