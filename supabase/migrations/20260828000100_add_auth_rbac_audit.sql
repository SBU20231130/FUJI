-- public training/raw 영역은 RLS가 켜져 있어도 anon grant가 남으면 접근면이 열릴 수 있어
-- anon 권한을 명시적으로 회수합니다. 기존 계산 데이터는 변경하지 않습니다.
revoke insert, update, delete, truncate on all tables in schema public from authenticated;

