-- app_user: 본인 프로필 또는 관리자는 조회, 변경은 관리자만 가능
alter table core.app_user enable row level security;
drop policy if exists app_user_select_self_or_admin on core.app_user;
create policy app_user_select_self_or_admin
on core.app_user
for select
to authenticated
using (
  user_id = (select auth.uid())
  or (select core.is_admin())
);

drop policy if exists app_user_update_admin_only on core.app_user;
create policy app_user_update_admin_only
on core.app_user
for update
to authenticated
using ((select core.is_admin()))
with check ((select core.is_admin()));

